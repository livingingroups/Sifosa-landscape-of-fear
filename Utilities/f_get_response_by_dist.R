#' Function: f_get_response_by_dist.R
#'
#' Compute Distance-Based Behavioral Responses.
#' This function calculates average behavioral response metrics based on distance thresholds between
#' Sifaka and Fosa using GPS and acceleration data.
#'
#' @author Maevatiana N. Ratsimbazafindranahaka (primary code author)
#' @author Damien Caillaud (code reviewer)
#'
#' @param search_values Numeric vector of distance thresholds to analyze.
#' @param time_range Time buffer (in seconds) around the encounter period for data extraction.
#' @param i Integer index of the encounter to process in `all_sifosa_encounters`.
#' @param all_sifosa_encounters Data frame containing encounter information between sifaka and fosa
#' @param acc_loc String indicating the path to ACC data files.
#' @param gps AM gps data as generated by s1a_make_ari_matrix.R
#' @param ddd 3D array of pairwise distances between individuals indexed by time as generated by s1a_make_ari_matrix.R
#' @param data_to_choose String specifying the metric name (column) in the ACC data to analyze (pitch or vedba).
#'
#' @return A tibble containing distance categories , averaged behavioral values, and metadata.
#' \itemize{
#'   \item \code{dist} Distance intervals.
#'   \item \code{value} Average value computed for the segment.
#'   \item \code{indA} Identifier for individual A.
#'   \item \code{indB} Identifier for individual B.
#'   \item \code{fosa_type} Fosa classification associated with the encounter.
#'   \item \code{duplicate} Duplicate encounter flag.
#'   \item \code{start} Start timestamps for each segment.
#'   \item \code{end} End timestamps for each segment.

library(lubridate)  # For handling date-time operations
library(tibble)     # For structured data output

f_get_response_by_dist <- function(search_values,
                                   time_range,
                                   i,
                                   all_sifosa_encounters,
                                   acc_loc,
                                   gps,
                                   ddd,
                                   data_to_choose,
                                   direction = "approach", season = "dry") {
  
  # Load current sifaka's ACC data
  curr.ind <- all_sifosa_encounters$indA[i]
  curr.accdata <- read.csv(paste0(
    acc_loc,
    curr.ind,
    '_',
    names(which.max(table(
      year(all_sifosa_encounters$start)
    ))),
    '_',
    season,
    '_regular.csv'
  ))
  curr.accdata$timestamps <- as.POSIXct(curr.accdata$DT_adj, tz = tz(all_sifosa_encounters$start))
  
  # Identify the indices for individuals A and B in the AM GPS dataset
  indA <- gps$ids$idx[which(gps$ids$id_code == all_sifosa_encounters$indA[i])]
  indB <- gps$ids$idx[which(gps$ids$id_code == all_sifosa_encounters$indB[i])]
  
  # Define time ranges for filtering GPS and ACC data
  gpsdata.range <- gps$timestamps >= all_sifosa_encounters$start[i] - time_range &
    gps$timestamps <= all_sifosa_encounters$end[i] + time_range
  accdata.range <- curr.accdata$timestamps >= all_sifosa_encounters$start[i] - time_range &
    curr.accdata$timestamps <= all_sifosa_encounters$end[i] + time_range
  
  # Extract relevant distance data, positions, and corresponding timestamps
  
  curr.ddd <- ddd[indA, indB, gpsdata.range]
  curr.timestamps <- gps$timestamps[gpsdata.range]
  curr.xs <- gps$xs[indA, gpsdata.range]
  curr.ys <- gps$ys[indA, gpsdata.range]

  # Handling case where the fossa did not left the max interval yet within the specified time_range (or was already within the max interval at the begining of the data section being analyzed)  
  buffer_right = time_range
  buffer_left = time_range
  # Add one hour until the fossa leaves
  while (is.na(tail(curr.ddd, 1)) || tail(curr.ddd, 1) < max(search_values)) {
    buffer_right = buffer_right+hours(1)
    # Define time ranges for filtering GPS and ACC data
    gpsdata.range <- gps$timestamps >= all_sifosa_encounters$start[i] - buffer_left &
      gps$timestamps <= all_sifosa_encounters$end[i] + buffer_right
    accdata.range <- curr.accdata$timestamps >= all_sifosa_encounters$start[i] - buffer_left &
      curr.accdata$timestamps <= all_sifosa_encounters$end[i] + buffer_right
    
    curr.ddd <- ddd[indA, indB, gpsdata.range]
    curr.timestamps <- gps$timestamps[gpsdata.range]
    curr.xs <- gps$xs[indA, gpsdata.range]
    curr.ys <- gps$ys[indA, gpsdata.range]
  }
  
  # Add one hour before until the fossa is outside at the start of the data section to work with
  while (is.na(curr.ddd[1]) || curr.ddd[1] < max(search_values)){
    buffer_left = buffer_left+hours(1)
    # Define time ranges for filtering GPS and ACC data
    gpsdata.range <- gps$timestamps >= all_sifosa_encounters$start[i] - buffer_left &
      gps$timestamps <= all_sifosa_encounters$end[i] + buffer_right
    accdata.range <- curr.accdata$timestamps >= all_sifosa_encounters$start[i] - buffer_left &
      curr.accdata$timestamps <= all_sifosa_encounters$end[i] + buffer_right
    
    curr.ddd <- ddd[indA, indB, gpsdata.range]
    curr.timestamps <- gps$timestamps[gpsdata.range]
    curr.xs <- gps$xs[indA, gpsdata.range]
    curr.ys <- gps$ys[indA, gpsdata.range]
  }
  
  if (direction == "approach") {
    # Get the responses during approach (decreasing distance)
    
    # Find the first occurrence where the distance falls at or below each threshold in search_values
    first_indices <- sapply(search_values, function(value) {
      match <- which(curr.ddd <= value)
      if (length(match) > 0) {
        return(match[1])  # First occurrence where distance is below the threshold
      } else {
        return(NA)        # No match found
      }
    })
    
    # Identify the last timestamp where distance is ≤ last distance threshold (i.e., the lowest dist thresh)
    last_index <- tail(which(curr.ddd <= tail(search_values, 1)), 1)
    
    # Combine first occurrence indices and the last index
    indices <- c(first_indices, last_index)
    # curr.ddd[indices] # Quick inspection
    
    # Give proper name to each interval
    dist = c(paste(search_values[-length(search_values)], "-", search_values[-1]),
             paste('≤', search_values[length(search_values)]))
    
  } else {
    # Get the responses during departure (increasing distance)
    
    # Find the last occurrence where the distance falls at or below each threshold in search_values
    last_indices <- sapply(search_values, function(value) {
      match <- which(curr.ddd <= value)
      if (length(match) > 0) {
        return(tail(match, 1))  # Last occurrence where distance is below the threshold
      } else {
        return(NA)              # No match found
      }
    })
    
    # Identify the first timestamp where distance is ≤ last distance threshold (i.e., the lowest dist thresh)
    first_index <- {
      match <- which(curr.ddd <= search_values[length(search_values)])
      if (length(match) > 0)
        match[1]
      else
        NA
    }
    
    # Combine last occurrence indices and the first index
    indices <- c(last_indices, first_index)
    # curr.ddd[indices] # Quick inspection
    
    # Give proper name to each interval
    indices <- sort(indices)
    search_values <- rev(search_values)
    dist = c(paste('≤', search_values[1]),
             paste(search_values[-length(search_values)], "-", search_values[-1]))
  }
  
  # Initialize a vector for storing averaged metric values per interval
  avg <- rep(NA, length(indices) - 1)
  
  if (data_to_choose == "movement") {
    # Compute average behavioral values for each distance range
     for (j in 1:(length(indices) - 1)) {
       # Check that both current and next index are not NA, ensuring valid time intervals
       if (!is.na(indices[j]) && !is.na(indices[j + 1])) {
         # Determine if the timestamps for the two indices differ.
         # This is to avoid having a zero-length interval when the timestamps are identical.
         # One of the reasons a zero-length interval exists is that approach/departure
         # may happens very quickly, crossing successive thresholds faster than the data time resolution.
         # This means that the first distance ≤ threshold1 and the first distance ≤ threshold2
         # may end up at the same time point
         if (curr.timestamps[indices[j]] != curr.timestamps[indices[j + 1]]) {
           # Define the time interval from the current distance interval start timestamp up to the next one (included, since for the displacement = location at the start of the next interval relative to the start of that interval)
           ddd.range.time <- curr.timestamps >= curr.timestamps[indices[j]] &
             curr.timestamps <= curr.timestamps[indices[j + 1]]
         } else {
           # If the timestamps are the same, extend the interval by one additional record to capture data
           ddd.range.time <- curr.timestamps >= curr.timestamps[indices[j]] &
             curr.timestamps <= curr.timestamps[indices[j] + 1]
         }
         
         # Calculate the displacement of the animal from the start of the interval to its end.

         xi <- curr.xs[ddd.range.time][1]
         yi <- curr.ys[ddd.range.time][1]
         xj <- tail(curr.xs[ddd.range.time], 1)
         yj <- tail(curr.ys[ddd.range.time], 1)


         # Get distances and store
         dists_ij <- sqrt((xi - xj)^2 + (yi - yj)^2)

         avg[j] <- dists_ij
         
       } else {
         # Otherwise, put NA
         
         avg[j] <- NA
         
       }
     }
  } else {
    for (j in 1:(length(indices) - 1)) {
      # Check that both current and next index are not NA, ensuring valid time intervals
      if (!is.na(indices[j]) && !is.na(indices[j + 1])) {
        # Determine if the timestamps for the two indices differ.
        # This is to avoid having a zero-length interval when the timestamps are identical.
        # One of the reasons a zero-length interval exists is that approach/departure
        # may happens very quickly, crossing successive thresholds faster than the data time resolution.
        # This means that the first distance ≤ threshold1 and the first distance ≤ threshold2
        # may end up at the same time point
        if (curr.timestamps[indices[j]] != curr.timestamps[indices[j + 1]]) {
          # Define the time interval from the current distance interval start timestamp up to (but not including) the next one
          ddd.range.time <- curr.accdata$timestamps >= curr.timestamps[indices[j]] &
            curr.accdata$timestamps < curr.timestamps[indices[j + 1]]
        } else {
          # If the timestamps are the same, extend the interval by one additional record to capture data
          ddd.range.time <- curr.accdata$timestamps >= curr.timestamps[indices[j]] &
            curr.accdata$timestamps < curr.timestamps[indices[j] + 1]
        }
        
        # Calculate the mean of the specified data within the determined time interval.
        # 'na.rm = TRUE' ensures that any NA values are excluded from the computation.
        avg[j] <- mean(curr.accdata[[data_to_choose]][ddd.range.time], na.rm = TRUE)
        
      } else {
        # Otherwise, put NA
        
        avg[j] <- NA
        
      }
    }
  }
  
  # Replace any NaN values with NA
  avg[is.nan(avg) | is.infinite(avg)] <- NA
  
  # Construct and return the results as a tibble
  return(
    tibble(
      dist = dist,
      value = avg,
      indA = all_sifosa_encounters$indA[i],
      indB = all_sifosa_encounters$indB[i],
      fosa_type = all_sifosa_encounters$fosa_type[i],
      duplicate = all_sifosa_encounters$duplicate[i],
      start = curr.timestamps[indices[1:(length(indices) - 1)]],
      end = curr.timestamps[indices[2:length(indices)]]
    )
  )
}

